/**
 * Lists whatever is in `public/homes` so the app can use it.
 *
 *   npm run photos:index
 *
 * Writes `src/lib/local-photos.ts`. A generated list rather than a directory
 * read at runtime, because the app renders on the server and on the client and
 * only one of those can see the filesystem — and because Vercel serves
 * `public/` as static files without a directory listing.
 *
 * Why local files exist at all: the stock photography is served from
 * images.unsplash.com, and plenty of networks block it. A listing with no
 * picture looks broken whoever's fault that is, so anything dropped in that
 * folder wins over the CDN.
 */
import { readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const folder = join(here, "..", "public", "homes");
const out = join(here, "..", "src", "lib", "local-photos.ts");

const IMAGE = /\.(jpe?g|png|webp|avif)$/i;

let files = [];
try {
  files = (await readdir(folder)).filter((name) => IMAGE.test(name)).sort();
} catch {
  // No folder yet, which is the same as no photos.
}

const body = `/**
 * Generated by scripts/index-photos.mjs. Do not edit by hand.
 *
 * Photos found in public/homes. When this is empty the app falls back to the
 * stock photography in images.ts; when it is not, these are used instead.
 *
 * Re-run \`npm run photos:index\` after adding or removing files.
 */
export const LOCAL_HOME_PHOTOS: string[] = [
${files.map((name) => `  ${JSON.stringify(`/homes/${name}`)},`).join("\n")}
];
`;

await writeFile(out, files.length === 0 ? body.replace("\n\n];", "\n];") : body);

if (files.length === 0) {
  console.log("No images in public/homes — the app will use the stock photos.");
  console.log("Drop .jpg/.png/.webp files in there and run this again.");
} else {
  console.log(`Indexed ${files.length} photo${files.length === 1 ? "" : "s"}:`);
  for (const name of files) console.log(`  ${name}`);
  console.log("\nRestart the dev server to pick them up.");
}
