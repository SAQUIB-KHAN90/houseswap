/**
 * Bundles the migrations a project has not had yet into one file to paste.
 *
 *   node scripts/bundle-pending.mjs 0004
 *
 * The Supabase SQL editor takes one paste at a time, and eleven round trips
 * through a browser is eleven chances to apply one out of order or skip one
 * after a timeout. This writes `supabase/pending.sql` instead: everything from
 * the given migration onwards, in order, with a marker between each so a
 * failure says which one it stopped in.
 *
 * It is a convenience, not a replacement for `supabase db push`. The files in
 * `migrations/` stay the source of truth, and this is generated from them.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const migrations = join(here, "..", "supabase", "migrations");

const from = process.argv[2] ?? "0004";

// 0006 writes to the `storage` schema, which only a real Supabase project has.
// It is included here on purpose: this file is for a real project.
const files = (await readdir(migrations))
  .filter((name) => name.endsWith(".sql"))
  .sort()
  .filter((name) => name >= from);

if (files.length === 0) {
  console.error(`No migrations at or after ${from}.`);
  process.exit(1);
}

const parts = [
  "-- Generated by scripts/bundle-pending.mjs. Do not edit.",
  `-- Migrations ${files[0]} to ${files[files.length - 1]}, in order.`,
  "--",
  "-- Paste the whole thing into the Supabase SQL editor and run it once.",
  "-- Every statement is written to be safe to run twice, so if it fails",
  "-- part way you can fix the cause and run the same file again.",
  "",
];

for (const name of files) {
  parts.push(
    "",
    `-- ${"=".repeat(70)}`,
    `-- ${name}`,
    `-- ${"=".repeat(70)}`,
    "",
    (await readFile(join(migrations, name), "utf8")).trim(),
    ""
  );
}

const out = join(here, "..", "supabase", "pending.sql");
await writeFile(out, parts.join("\n"));

console.log(`Wrote supabase/pending.sql with ${files.length} migrations:`);
for (const name of files) console.log(`  ${name}`);
